// Bundles hand-written recipes (recipes/*.json), the web compiler and the phone RE template
// engine (scripts/re/lib/template.ts) into the Convex deploy.
// Convex functions cannot read the filesystem, and a static import of a missing file breaks the
// bundle, so this writes two small modules that only reference files that exist.
// Run before deploying:  node convex/sync.recipes.mjs && npx convex dev --once
// (Convex skips this file: its name has two dots.)
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..");

// 1. Hand recipes.
const recipesDir = join(root, "recipes");
const files = existsSync(recipesDir)
  ? readdirSync(recipesDir).filter((f) => f.endsWith(".json")).sort()
  : [];
const recipes = [];
for (const f of files) {
  try {
    const parsed = JSON.parse(readFileSync(join(recipesDir, f), "utf8"));
    if (!parsed || typeof parsed !== "object" || !Array.isArray(parsed.tools)) {
      console.warn(`skip recipes/${f}: no tools array`);
      continue;
    }
    if (!parsed.appSlug) parsed.appSlug = f.replace(/\.json$/, "");
    recipes.push(parsed);
    console.log(`hand recipe: ${parsed.appSlug} v${parsed.version ?? 1} (${parsed.tools.length} tools)`);
  } catch (e) {
    console.warn(`skip recipes/${f}: ${e.message}`);
  }
}
writeFileSync(
  join(here, "lib", "handRecipes.ts"),
  `// GENERATED by convex/sync.recipes.mjs from recipes/*.json. Do not edit by hand.\n` +
    `import type { Recipe } from "../../src/lib/contract";\n\n` +
    `export const HAND_RECIPES: Recipe[] = ${JSON.stringify(recipes, null, 2)} as unknown as Recipe[];\n`,
);

// 2. Web compiler.
const compilerPath = join(root, "src", "lib", "compiler", "compile.ts");
const hasCompiler = existsSync(compilerPath);
writeFileSync(
  join(here, "lib", "compilerShim.ts"),
  `// GENERATED by convex/sync.recipes.mjs. Do not edit by hand.\n` +
    (hasCompiler
      ? `import * as compilerModule from "../../src/lib/compiler/compile";\n` +
        `export const compileCapture: undefined | ((...args: any[]) => any) = (compilerModule as any).compileCapture;\n` +
        `export const refineWithLLM: undefined | ((recipe: any, opts: any) => Promise<any>) = (compilerModule as any).refineWithLLM;\n` +
        `export const HAS_COMPILER = typeof compileCapture === "function";\n`
      : `// src/lib/compiler/compile.ts did not exist at sync time; the pipeline uses its local fallback.\n` +
        `export const compileCapture: undefined | ((...args: any[]) => any) = undefined;\n` +
        `export const refineWithLLM: undefined | ((recipe: any, opts: any) => Promise<any>) = undefined;\n` +
        `export const HAS_COMPILER = false;\n`),
);
console.log(`compiler: ${hasCompiler ? "src/lib/compiler/compile.ts" : "fallback (not found)"}`);

// 3. Phone RE template engine ({{x|fallback}}, {{$uuid}}, {{#each}}, login_api token rotation).
const templatePath = join(root, "scripts", "re", "lib", "template.ts");
const hasTemplate = existsSync(templatePath);
writeFileSync(
  join(here, "lib", "templateShim.ts"),
  `// GENERATED by convex/sync.recipes.mjs. Do not edit by hand.\n` +
    (hasTemplate
      ? `export { runTool, ensureLogin, renderRequest, send } from "../../scripts/re/lib/template";\n` +
        `export type { RunState, ToolResult } from "../../scripts/re/lib/template";\n` +
        `export const HAS_TEMPLATE = true;\n`
      : `// scripts/re/lib/template.ts did not exist at sync time; login_api recipes use the built-in renderer.\n` +
        `export const runTool: any = undefined;\nexport const ensureLogin: any = undefined;\n` +
        `export const renderRequest: any = undefined;\nexport const send: any = undefined;\n` +
        `export type RunState = { login?: Record<string, unknown> };\nexport type ToolResult = any;\n` +
        `export const HAS_TEMPLATE = false;\n`),
);
console.log(`template engine: ${hasTemplate ? "scripts/re/lib/template.ts" : "built-in only (not found)"}`);
