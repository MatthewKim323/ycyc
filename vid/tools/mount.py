#!/usr/bin/env python3
"""python3 tools/mount.py  ->  index.html from assets/timing.json.

Mounts one host per scene at its slot, the voice stem (assets/audio/dialogue.wav), the effects stem
(assets/audio/fx.wav) when present, and the shared kit. Creates a placeholder scene for any slot whose
composition does not exist yet, so the film always plays end to end.
"""
import json
from pathlib import Path

L = Path(__file__).resolve().parents[1]
t = json.loads((L / "assets" / "timing.json").read_text())
total = t["total"]
hosts, z = [], 10
for sid, s in t["scenes"].items():
    comp = L / "compositions" / f"{sid}.html"
    if not comp.exists():
        comp.write_text(f'''<template>
  <style>#root {{ position: absolute; inset: 0; }} #{sid}-ph {{ position: absolute; inset: 0; display: flex; align-items: center; justify-content: center; font: 600 64px "Inter", sans-serif; color: #8a8a90; }}</style>
  <div id="root" data-composition-id="{sid}" data-width="1920" data-height="1080">
    <div id="{sid}-wrap" class="clip k-canvas" data-start="0" data-duration="{s['duration']:.3f}" data-track-index="0"><p id="{sid}-ph">{sid}</p></div>
  </div>
  <script>window.__timelines["{sid}"] = gsap.timeline({{ paused: true }});</script>
</template>
''')
    hosts.append(f'      <div style="z-index: {z}" id="{sid}" data-composition-id="{sid}" data-composition-src="compositions/{sid}.html" data-start="{s["start"]:.3f}" data-duration="{s["duration"]:.3f}" data-track-index="1" data-track-kind="graphics" data-width="1920" data-height="1080"></div>')
import sys
fx = (L / "assets" / "audio" / "fx.wav").exists()
MIX = "--mix" in sys.argv and (L / "assets" / "audio" / "mix.wav").exists()  # render: the mastered mix only
audio = [f'      <audio id="dialogue" src="assets/audio/dialogue.wav" data-start="0" data-duration="{total:.3f}" data-track-index="5" data-volume="1"></audio>']
if MIX:
    audio = [f'      <audio id="mix" src="assets/audio/mix.wav" data-start="0" data-duration="{total:.3f}" data-track-index="5" data-volume="1"></audio>']
elif fx:
    audio.append(f'      <audio id="fx" src="assets/audio/fx.wav" data-start="0" data-duration="{total:.3f}" data-track-index="6" data-volume="1"></audio>')
html = f'''<!doctype html>
<html lang="en" data-resolution="landscape">
  <head>
    <meta charset="UTF-8" />
    <meta name="viewport" content="width=1920, height=1080" />
    <script src="https://cdn.jsdelivr.net/npm/gsap@3.14.2/dist/gsap.min.js"></script>
    <script src="https://cdn.jsdelivr.net/npm/gsap@3.14.2/dist/CustomEase.min.js"></script>
    <script src="https://cdn.jsdelivr.net/npm/gsap@3.14.2/dist/SplitText.min.js"></script>
    <script src="https://cdn.jsdelivr.net/npm/gsap@3.14.2/dist/Flip.min.js"></script>
    <script src="https://cdn.jsdelivr.net/npm/lottie-web@5.12.2/build/player/lottie_light.min.js"></script>
    <script src="assets/pattern-waves.js"></script>
    <script src="assets/lordicons/icons.js"></script>
    <script src="assets/kit.js"></script>
    <link rel="stylesheet" href="assets/kit.css" />
    <style>
      * {{ margin: 0; padding: 0; box-sizing: border-box; }}
      html, body {{ margin: 0; width: 1920px; height: 1080px; overflow: hidden; background: #000; }}
      #root {{ width: 100%; height: 100%; }}
    </style>
  </head>
  <body>
    <!-- Generated by tools/mount.py from assets/timing.json. Scenes: compositions/<id>.html (see ../README.md). -->
    <div id="root" data-composition-id="main" data-start="0" data-duration="{total:.3f}" data-width="1920" data-height="1080">
{chr(10).join(hosts)}

{chr(10).join(audio)}
    </div>
    <script>
      const tl = gsap.timeline({{ paused: true }});
      window.__timelines["main"] = tl;
      tl.seek(0);
    </script>
  </body>
</html>
'''
(L / "index.html").write_text(html)
print(f"mix only: {MIX}") if MIX else None
print(f"mounted {len(hosts)} scenes, {total:.2f}s, fx={'yes' if fx else 'no'}")
