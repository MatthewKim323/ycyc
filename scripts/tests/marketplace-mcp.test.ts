/// <reference types="node" />
import assert from "node:assert/strict";
import { test } from "node:test";
import { getFunctionName } from "convex/server";
import { callUserAppTool, handleMcpPost } from "../../convex/lib/mcp";
import { claudeTurnArguments, codexModelCatalog, codexTurnConfiguration } from "../../convex/lib/providerTurn";
import { SITE_URL } from "../../convex/lib/env";

const token = "private-marketplace-capability-a";
type Call = { name: string; args: Record<string, any> };

function fixture() {
  const queries: Call[] = [], actions: Call[] = [], mutations: Call[] = [];
  const installed = { integrations: [{ id: "deepwiki", enabled: true, readOnly: true }, { id: "yuzu", native: true }] };
  const raw = { user: { _id: "user-a" }, connections: [], live: [] as { conn: Record<string, unknown>; recipeJson: string }[], publicRecipes: [], discovered: [] };
  const definitions = { pluginId: "deepwiki", tools: [{ name: "read_wiki_structure", inputSchema: { type: "object", properties: { repoName: { type: "string" } } } }] };
  let result: unknown = { pluginId: "deepwiki", data: { sections: ["Overview"] } };
  let failure: Error | null = null;
  const ctx = {
    runQuery: async (ref: Parameters<typeof getFunctionName>[0], args: Record<string, any>) => {
      const name = getFunctionName(ref);
      queries.push({ name, args });
      if (name === "mcpData:context") return args.token === token ? raw : null;
      if (name === "marketplace:installed") return installed;
      if (name === "mcpData:names") return {};
      if (name === "approvals:activeGrant") return null;
      if (name === "approvals:get") return { status: "denied" };
      throw new Error(`Unexpected query ${name}`);
    },
    runAction: async (ref: Parameters<typeof getFunctionName>[0], args: Record<string, any>) => {
      const name = getFunctionName(ref);
      actions.push({ name, args });
      if (failure) throw failure;
      if (name === "marketplaceActions:tools") return definitions;
      if (name === "marketplaceActions:call") return result;
      throw new Error(`Unauthorized action ${name}`);
    },
    runMutation: async (ref: Parameters<typeof getFunctionName>[0], args: Record<string, any>) => {
      const name = getFunctionName(ref);
      assert.ok(["mcpData:saveSession", "approvals:create"].includes(name), "agents must never install, uninstall or enable integrations");
      mutations.push({ name, args });
      return "native-approval-a";
    },
  };
  const send = async (method: string, params: Record<string, unknown> = {}, capability = token) => {
    const response = await handleMcpPost(ctx as unknown as Parameters<typeof handleMcpPost>[0], new Request(`${SITE_URL}/mcp/${capability}`, {
      method: "POST", headers: { "content-type": "application/json" }, body: JSON.stringify({ jsonrpc: "2.0", id: 1, method, params }),
    }));
    return { status: response.status, message: await response.json() as any };
  };
  return { queries, actions, mutations, installed, definitions, send, ctx, raw,
    call: (name: string, args: unknown = {}, capability = token) => send("tools/call", { name, arguments: args }, capability),
    result: (value: unknown) => { result = value; },
    fail: (error: Error) => { failure = error; },
  };
}

test("MCP exposes installed-plugin discovery and calls without agent installation tools", async () => {
  const f = fixture();
  const { message } = await f.send("tools/list");
  for (const name of ["list_plugins", "plugin_tools", "call_plugin_tool"]) {
    const definitions = message.result.tools.filter((tool: any) => tool.name === name);
    assert.equal(definitions.length, 1);
    assert.equal(definitions[0].inputSchema.additionalProperties, false);
    assert.equal(definitions[0].annotations.readOnlyHint, name !== "call_plugin_tool");
  }
  for (const name of ["install_plugin", "uninstall_plugin", "enable_plugin", "disable_plugin"]) {
    assert.ok(!message.result.tools.some((tool: any) => tool.name === name));
    assert.equal((await f.call(name, { pluginId: "deepwiki" })).message.error.code, -32602);
  }
  assert.equal(f.actions.length, 0);
  assert.equal(f.mutations.length, 0);
});

test("optional learned-write request IDs are preserved exactly and never autogenerated", async () => {
  const f = fixture();
  const args = { pluginId: "native-private-tools", tool: "write_note", args: { note: "new note" }, requestId: "stable_action_123" };
  await f.call("call_plugin_tool", args);
  assert.deepEqual(f.actions[0], { name: "marketplaceActions:call", args: { token, ...args } });
  const { requestId: _requestId, ...read } = args;
  await f.call("call_plugin_tool", read);
  assert.deepEqual(f.actions[1], { name: "marketplaceActions:call", args: { token, ...read } });
  assert.ok(!Object.hasOwn(f.actions[1].args, "requestId"));
  const before = f.actions.length;
  for (const requestId of ["", "short", "contains spaces", "x".repeat(129), 123]) {
    assert.equal((await f.call("call_plugin_tool", { ...args, requestId })).message.error.code, -32602);
  }
  assert.equal(f.actions.length, before);
});

test("the native marketplace adapter reuses the current user's existing app-write approval path", async () => {
  const f = fixture();
  f.raw.live.push({ conn: { _id: "connection-a", userId: "user-a", appSlug: "myfitnesspal" }, recipeJson: JSON.stringify({ tools: [
    { name: "log_food", title: "Log food", description: "Log food", kind: "write", inputSchema: { type: "object" } },
  ] }) });
  const ctx = f.ctx as unknown as Parameters<typeof callUserAppTool>[0];
  const result = await callUserAppTool(ctx, token, "myfitnesspal", "log_food", { food: "oats" });
  assert.equal(result.isError, true);
  assert.match(result.content[0].text, /denied/);
  assert.deepEqual(f.mutations.filter((mutation) => mutation.name === "approvals:create").map((mutation) => ({
    userId: mutation.args.userId, connectionId: mutation.args.connectionId, assistant: mutation.args.assistant, tool: mutation.args.tool, args: JSON.parse(mutation.args.argsJson),
  })), [{ userId: "user-a", connectionId: "connection-a", assistant: "ycyc", tool: "log_food", args: { food: "oats" } }]);
  assert.equal(f.actions.length, 0, "denied native writes must not enter an alternate transport");
  const before = f.mutations.length;
  await assert.rejects(callUserAppTool(ctx, "unknown-capability", "myfitnesspal", "log_food", {}), /Unknown yuzu link/);
  await assert.rejects(callUserAppTool(ctx, token, "myfitnesspal", "log_food__other", {}), /Invalid app tool/);
  assert.equal(f.mutations.length, before);
});

test("installed integrations use only the URL capability and preserve safe native metadata", async () => {
  const f = fixture();
  const { message } = await f.call("list_plugins", { token: "foreign-capability", operation: "install", pluginId: "untrusted" });
  assert.deepEqual(f.queries.filter((query) => query.name === "marketplace:installed"), [{ name: "marketplace:installed", args: { token } }]);
  assert.deepEqual(JSON.parse(message.result.content[0].text), f.installed);
  assert.equal(f.actions.length, 0);
  assert.equal(f.mutations.length, 0);
});

